/** Resolves when a grid cell shows `text` (the accessibility table glide keeps in sync). */
async function expectCell(page: Page, text: string, timeout = 30_000) {
  await expect(cells(page).filter({ hasText: text }).first()).toBeAttached({ timeout });
}

const ROW_MARKER_WIDTH = 48;
const HEADER_HEIGHT = 36;
const ROW_HEIGHT = 34;

function selectedColumn(page: Page): Promise<number> {
  return page
    .locator('table[role="grid"] td[role="gridcell"][aria-selected="true"]')
    .first()
    .getAttribute('aria-colindex')
    .then((value) => Number(value ?? '0'));
}

/** Selects the cell of column `name` in data row `row` with the keyboard (as T468). */
async function selectCell(page: Page, name: string, row = 0): Promise<void> {
  const canvas = page.locator('.ob-grid [data-testid="data-grid-canvas"]');
  const box = await canvas.boundingBox();
  if (box === null) throw new Error('grid not laid out');
  await page.mouse.click(
    box.x + ROW_MARKER_WIDTH + 24,
    box.y + HEADER_HEIGHT + ROW_HEIGHT * row + ROW_HEIGHT / 2,
  );
  // Explicit timeouts: inside `toPass` an expectation has none by default. The click selects
  // the first column (the accessibility table follows on a later frame).
  await expect.poll(() => selectedColumn(page), { timeout: 5_000 }).toBe(1);
  await expect
    .poll(() => page.evaluate(() => document.activeElement?.closest('.ob-grid') != null), {
      timeout: 5_000,
    })
    .toBe(true);
  for (let step = 0; step < 20; step += 1) {
    const target = Number(await header(page, name).getAttribute('aria-colindex'));
    const current = await selectedColumn(page);
    if (current === target) return;
    await page.keyboard.press(current > target ? 'ArrowLeft' : 'ArrowRight');
    // The accessibility table follows the selection on the next frame.
    await expect.poll(() => selectedColumn(page), { timeout: 5_000 }).not.toBe(current);
  }
  throw new Error(`column ${name} not reached`);
}

/** The column menu of `name`: Shift+F10 on one of its cells (the keyboard way, F§1.3). */
async function columnMenu(page: Page, name: string): Promise<Locator> {
  const menu = page.getByRole('menu', { name: `Field menu: ${name}` });
  // Right after a load glide may still take the focus back on the next frame (as T207): retry.
  await expect(async () => {
    if ((await page.getByRole('menu').count()) > 0) {
      await page.keyboard.press('Escape');
      await expect(page.getByRole('menu')).toHaveCount(0, { timeout: 2_000 });
    }
    await selectCell(page, name);
    await page.evaluate(
      () =>
        new Promise<void>((resolve) => {
          requestAnimationFrame(() => {
            resolve();
          });
        }),
    );
    await page.keyboard.press('Shift+F10');
    await expect(menu).toBeVisible({ timeout: 2_000 });
  }).toPass({ timeout: 20_000 });
  return menu;
}


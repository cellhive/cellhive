/**
 * Repositories of `@cellhive/server-core`, one instance each, injected by
 * class: `@Inject(UsersRepository) users: UsersRepository`. They are plain
 * classes (no Nest decorators) so that the CLI builds them the same way.
 */
@Global()
@Module({
  providers: REPOSITORIES.map((repository): Provider => ({
    provide: repository,
    inject: [DB],
    useFactory: (db: Db) => new repository(db),
  })),
  exports: [...REPOSITORIES],
})
export class RepositoriesModule {}

/**
 * Generates `src/unaccent-rules.ts` from PostgreSQL's `unaccent.rules`, so
 * that the in-memory evaluator strips accents exactly like `meta.f_unaccent`
 * (SPEC §5.2). The integration harness in `packages/server-core` compares the
 * generated table with the database and fails on drift.
 *
 * The table ships in a compact form (T1000, FRONTEND §11.1: about a quarter
 * of the plain list once gzipped): runs of consecutive code points, decoded
 * by `src/unaccent.ts`. The plain list, one rule per line, goes to
 * `test/unaccent-rules.plain.ts`; the unit test checks that the compact
 * table decodes to exactly those rules.
 *
 * Usage (rules file of the PostgreSQL image the project runs, ADR-19):
 *   docker run --rm postgres:18 cat /usr/share/postgresql/18/tsearch_data/unaccent.rules > /tmp/unaccent.rules
 *   node packages/filter-dsl/scripts/generate-unaccent-rules.ts /tmp/unaccent.rules
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [source] = process.argv.slice(2);
if (source === undefined) {
  process.stderr.write('Usage: generate-unaccent-rules.ts <path to unaccent.rules>\n');
  process.exit(2);
}

/** Characters that would be invisible or confusing in the generated source. */
const ESCAPE = /[\p{Z}\p{C}\p{M}"\\]/u;

function literal(text: string): string {
  let out = '';
  for (const char of text) {
    out += ESCAPE.test(char)
      ? `\\u{${(char.codePointAt(0) ?? 0).toString(16).toUpperCase()}}`
      : char;
  }
  return out;
}

/**
 * Parses one rule the way contrib/unaccent does: the source is the first
 * whitespace-delimited token; the optional target is either a token or a
 * double-quoted string in which `""` stands for one `"`.
 */
function parseRule(line: string): [string, string] | null {
  const match = /^\s*(\S+)(?:\s+(?:"((?:[^"]|"")*)"|(\S+)))?\s*$/u.exec(line);
  if (match === null) {
    if (line.trim() === '') return null;
    throw new Error(`Unparsable rule: ${JSON.stringify(line)}`);
  }
  const [, from = '', quoted, bare] = match;
  return [from, quoted === undefined ? (bare ?? '') : quoted.replaceAll('""', '"')];
}

/** The rules in file order: source character, replacement (`''`: deleted). */
const rules: [string, string][] = [];
for (const line of readFileSync(source, 'utf8').split('\n')) {
  const rule = parseRule(line);
  if (rule === null) continue;
  const [from, to] = rule;
  if (String.fromCodePoint(from.codePointAt(0) ?? 0) !== from) {
    throw new Error(`Only single-character sources are supported: ${JSON.stringify(line)}`);
  }
  if (/[\t\n]/u.test(to))
    throw new Error(`Tab or newline in a replacement: ${JSON.stringify(line)}`);
  rules.push([from, to]);
}

/** Code point of a one-character string, `null` for any other. */
function single(text: string): number | null {
  const code = text.codePointAt(0);
  return code !== undefined && String.fromCodePoint(code) === text ? code : null;
}

/**
 * The compact form, one run per line: `<gap><kind><length>\t<replacement>`.
 * `<gap>` is the distance (base 36) from the first code point of the line
 * before (from 0 on the first line); no `<kind><length>`: one code point;
 * `*<n>`: n consecutive code points with the same replacement; `+<n>`: n
 * consecutive code points whose one-character replacements are consecutive
 * too (`Ａ`…`Ｚ` → `A`…`Z`), the first one written. An empty replacement
 * deletes the characters (combining marks).
 */
function compact(): { lines: string[]; runs: number } {
  const sorted = rules
    .map(([from, to]) => [from.codePointAt(0) ?? 0, to] as const)
    .sort((a, b) => a[0] - b[0]);
  const lines: string[] = [];
  let previous = 0;
  let index = 0;
  while (index < sorted.length) {
    const [code, to] = sorted[index] ?? [0, ''];
    const at = (offset: number) => sorted[index + offset];
    let same = 1;
    while (at(same)?.[0] === code + same && at(same)?.[1] === to) same += 1;
    const first = single(to);
    let step = 1;
    if (same === 1 && first !== null) {
      while (at(step)?.[0] === code + step && single(at(step)?.[1] ?? '') === first + step) {
        step += 1;
      }
    }
    const length = Math.max(same, step);
    const kind = length === 1 ? '' : `${same > 1 ? '*' : '+'}${length.toString(36)}`;
    lines.push(`${(code - previous).toString(36)}${kind}\t${literal(to)}`);
    previous = code;
    index += length;
  }
  return { lines, runs: lines.length };
}

const header = `// Generated by scripts/generate-unaccent-rules.ts from PostgreSQL 18 unaccent.rules. Do not edit.
// Source: PostgreSQL contrib/unaccent (PostgreSQL License). ${String(rules.length)} rules.`;

const { lines, runs } = compact();
writeFileSync(
  resolve(import.meta.dirname, '../src/unaccent-rules.ts'),
  `${header}

/**
 * \`unaccent.rules\` of PostgreSQL 18 in ${String(runs)} runs of consecutive code
 * points (decoded by \`unaccent.ts\`), one per line:
 * \`<gap><kind><length>\\t<replacement>\`. \`<gap>\`: distance in base 36 from the
 * first code point of the line before (from 0 on the first line). No
 * \`<kind><length>\`: one code point; \`*<n>\`: n code points with the same
 * replacement; \`+<n>\`: n code points whose one-character replacements follow
 * each other (the first one written). An empty replacement deletes the
 * characters (combining marks).
 */
export const UNACCENT_RULES =
  "${lines.join('\\n')}";
`,
);

writeFileSync(
  resolve(import.meta.dirname, '../test/unaccent-rules.plain.ts'),
  `${header}

/**
 * \`unaccent.rules\` of PostgreSQL 18 as the file lists them: one rule per line,
 * \`<char>\\t<replacement>\`, or \`<char>\` alone when the character is deleted
 * (combining marks). The compact table of \`src/unaccent-rules.ts\` must decode
 * to exactly these rules (\`test/unaccent.test.ts\`).
 */
export const PLAIN_UNACCENT_RULES =
  "${rules.map(([from, to]) => `${literal(from)}${to === '' ? '' : `\\t${literal(to)}`}`).join('\\n')}";
`,
);
process.stdout.write(`Wrote ${String(rules.length)} rules in ${String(runs)} runs\n`);
